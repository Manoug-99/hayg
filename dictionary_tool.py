def extract_from_raw_words_js(raw_js_path='js/words.js'):
    """Extracts raw data from original words.js if it was unencrypted."""
    with open(raw_js_path, 'r', encoding='utf-8') as f:
        content = f.read()

    # Check if already encrypted
    enc_match = re.search(r'const _P\s*=\s*"([^"]+)"', content)
    if enc_match:
        return decrypt_payload(enc_match.group(1))

    # Helper to parse JS object/array into JSON
    def parse_js(var_name, is_obj=False):
        pattern = rf'const {var_name}\s*=\s*([\[\{{].*?[\]\}}]);'
        m = re.search(pattern, content, re.DOTALL)
        if not m:
            return {} if is_obj else []
        raw = m.group(1)
        # Remove comments
        raw = re.sub(r'//.*', '', raw)
        raw = re.sub(r'/\*.*?\*/', '', raw, flags=re.DOTALL)
        # Fix trailing commas
        raw = re.sub(r',\s*([\]\}])', r'\1', raw)
        # Quote keys
        raw = re.sub(r'(?<=[{,\n\s])([a-zA-Z0-9_]+)\s*:', r'"\1":', raw)
        return json.loads(raw)

    return {
        'typingParagraphs': parse_js('typingParagraphs'),
        'targetWords': parse_js('targetWords'),
        'ztypeWords': parse_js('ztypeWords', is_obj=True),
        'typingWords': parse_js('typingWords'),
        'PUZZLES': parse_js('PUZZLES'),
        'wordleWords': parse_js('wordleWords', is_obj=True)
    }

def print_stats(data):
    print("\n" + "="*50)
    print("📊 Hayg Dictionary Statistics:")
    print("="*50)
    print(f"• Typing Paragraphs: {len(data.get('typingParagraphs', []))}")
    print(f"• Typing Words:      {len(data.get('typingWords', []))}")
    print(f"• Target Words:      {len(data.get('targetWords', []))}")
    print(f"• Spelling Puzzles:  {len(data.get('PUZZLES', []))}")
    
    zw = data.get('ztypeWords', {})
    print(f"• ZType Words:       Easy: {len(zw.get('easy', []))}, Med: {len(zw.get('medium', []))}, Hard: {len(zw.get('hard', []))}")
    
    ww = data.get('wordleWords', {})
    print(f"• Wordle Levels:")
    for k in sorted(ww.keys(), key=lambda x: int(x) if str(x).isdigit() else str(x)):
        print(f"   - Level {k} letters: {len(ww[k])} words")
    print("="*50 + "\n")

def export_json(data, path='dictionary_data.json'):
    with open(path, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    print(f"✅ Decrypted dictionary saved to: {path}")

def import_json(path='dictionary_data.json'):
    if not os.path.exists(path):
        print(f"❌ File not found: {path}")
        return None
    with open(path, 'r', encoding='utf-8') as f:
        return json.load(f)

def build_encrypted_js(data, js_path='js/words.js'):
    enc_b64 = encrypt_dict(data)
    js_content = generate_js_content(enc_b64)
    with open(js_path, 'w', encoding='utf-8') as f:
        f.write(js_content)
    print(f"🔒 Encrypted dictionary compiled and saved to: {js_path}")

def main_menu():
    # Load current dictionary
    js_path = os.path.join('js', 'words.js')
    json_path = 'dictionary_data.json'
    
    current_data = None
    if os.path.exists(js_path):
        try:
            current_data = extract_from_raw_words_js(js_path)
        except Exception as e:
            print(f"⚠️ Could not read {js_path}: {e}")
    
    if current_data is None and os.path.exists(json_path):
        current_data = import_json(json_path)

    if current_data is None:
        print("❌ Could not find dictionary in js/words.js or dictionary_data.json.")
        return

    while True:
        print("\n==============================================")
        print("🛡️  HAYG DICTIONARY ENCRYPTION & MANAGEMENT TOOL")
        print("==============================================")
        print("[1] 📊 View Dictionary Statistics")
        print("[2] 🔓 Decrypt & Export to dictionary_data.json (Editable JSON)")
        print("[3] 🔒 Encrypt dictionary_data.json -> js/words.js")
        print("[4] ➕ Add Wordle Word(s)")
        print("[5] ➕ Add Spelling Bee Puzzle")
        print("[6] ➕ Add ZType Word(s)")
        print("[7] ➕ Add Typing Paragraph / Word")
        print("[8] 💾 Save and Encrypt current in-memory data to js/words.js")
        print("[0] 🚪 Exit")
        print("----------------------------------------------")
        choice = input("Enter option [0-8]: ").strip()

        if choice == '1':
            print_stats(current_data)
        elif choice == '2':
            export_json(current_data, json_path)
            print("💡 You can now edit 'dictionary_data.json' in any text editor, then choose Option 3 to re-encrypt.")
        elif choice == '3':
            loaded = import_json(json_path)
            if loaded:
                current_data = loaded
                build_encrypted_js(current_data, js_path)
        elif choice == '4':
            ww = current_data.setdefault('wordleWords', {})
            print(f"Current levels: {list(ww.keys())}")
            lvl = input("Enter word length / level (e.g. 3, 5, 7 or new level): ").strip()
            if lvl:
                words_input = input("Enter word(s) separated by comma or space: ").strip()
                if words_input:
                    new_words = [w.strip().upper() for w in re.split(r'[, \n]+', words_input) if w.strip()]
                    lvl_list = ww.setdefault(lvl, [])
                    added = 0
                    for nw in new_words:
                        if nw not in lvl_list:
                            lvl_list.append(nw)
                            added += 1
                    print(f"✅ Added {added} new words to Wordle level {lvl}.")
                    build_encrypted_js(current_data, js_path)
                    export_json(current_data, json_path)
        elif choice == '5':
            puzzles = current_data.setdefault('PUZZLES', [])
            main_w = input("Enter Main Word (e.g. ՔԱՂԱՔԱԿՐԹՈՒԹԻՒՆ): ").strip().upper()
            if main_w:
                sub_input = input("Enter Sub-words separated by comma: ").strip()
                sub_words = [sw.strip().upper() for sw in sub_input.split(',') if sw.strip()]
                puzzles.append({'mainWord': main_w, 'subWords': sub_words})
                print(f"✅ Added puzzle '{main_w}' with {len(sub_words)} sub-words.")
                build_encrypted_js(current_data, js_path)
                export_json(current_data, json_path)
        elif choice == '6':
            zw = current_data.setdefault('ztypeWords', {'easy': [], 'medium': [], 'hard': []})
            diff = input("Select difficulty (easy / medium / hard): ").strip().lower()
            if diff in zw:
                words_input = input(f"Enter words for {diff} separated by comma: ").strip()
                new_words = [w.strip() for w in words_input.split(',') if w.strip()]
                added = 0
                for nw in new_words:
                    if nw not in zw[diff]:
                        zw[diff].append(nw)
                        added += 1
                print(f"✅ Added {added} words to ZType {diff}.")
                build_encrypted_js(current_data, js_path)
                export_json(current_data, json_path)
            else:
                print("❌ Invalid difficulty.")
        elif choice == '7':
            print("[A] Add Typing Paragraph\n[B] Add Typing Word")
            sub_c = input("Choice: ").strip().upper()
            if sub_c == 'A':
                tp = current_data.setdefault('typingParagraphs', [])
                para = input("Paste paragraph text: ").strip()
                if para:
                    tp.append(para)
                    print("✅ Added paragraph.")
                    build_encrypted_js(current_data, js_path)
                    export_json(current_data, json_path)
            elif sub_c == 'B':
                tw = current_data.setdefault('typingWords', [])
                words_input = input("Enter word(s) separated by comma: ").strip()
                new_words = [w.strip() for w in words_input.split(',') if w.strip()]
                added = 0
                for nw in new_words:
                    if nw not in tw:
                        tw.append(nw)
                        added += 1
                print(f"✅ Added {added} typing words.")
                build_encrypted_js(current_data, js_path)
                export_json(current_data, json_path)
        elif choice == '8':
            build_encrypted_js(current_data, js_path)
            export_json(current_data, json_path)
        elif choice == '0':
            print("👋 Goodbye!")
            break
        else:
            print("❌ Invalid choice. Please select 0-8.")

